// Run with playwright-cli run-code --filename=scripts/verify_uiux_desktop.js
async (page) => {
  const checks = [];
  const errors = [];
  const dataRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    const url = new URL(request.url());
    if (url.pathname.startsWith('/api/') || !['127.0.0.1', 'localhost'].includes(url.hostname)) dataRequests.push(url.origin + url.pathname);
  });
  const verify = async (fn, name) => { for(let attempt=0; attempt<50; attempt++) { if(await fn()) {checks.push(name); return;} await page.waitForTimeout(50); } throw new Error(name); };
  const shot = name => page.screenshot({ path: `output/playwright/final-uiux-${name}.png`, fullPage: true });
  const nav = name => page.getByRole('navigation', {name:'워크스페이스 메뉴'}).getByRole('link', {name:new RegExp('^'+name)}).click();
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:8822/workspace');
  await page.getByRole('heading', {name:'나에게 필요한 일, 오늘도 K:LINK와 함께.'}).waitFor();
  await verify(async () => await page.locator('.kl-benefit-card').count() === 3, 'home recommends three synthetic eligible cards');
  await verify(async () => (await page.locator('.kl-overview-stats').innerText()).replace(/\s/g,'').includes('3건추가로확인할혜택2건'), 'home eligibility counts are 3 eligible and 2 review');
  await shot('home-desktop');
  await page.getByRole('button', {name:'자녀 돌봄 지원금 저장',exact:true}).click();
  await verify(async () => await page.getByRole('button',{name:'자녀 돌봄 지원금 저장 취소'}).getAttribute('aria-pressed')==='true', 'save benefit toggles state');
  await page.locator('.kl-quick-nav a').first().click();
  await verify(async () => await page.locator('.kl-benefit-card').count()===1, 'saved benefit persists across navigation');
  await page.getByRole('tab',{name:/전체 혜택/}).click();
  await verify(async () => await page.locator('.kl-benefit-card').count()===6, 'all benefits shows six fixtures');
  const eligible = page.getByRole('tab',{name:/조건 충족/});
  await eligible.focus(); await page.keyboard.press('ArrowRight');
  await verify(async () => await page.getByRole('tab',{name:/추가 확인/}).getAttribute('aria-selected')==='true', 'arrow keys activate benefit status tabs');
  await verify(async () => await page.locator('.kl-benefit-card').count()===2, 'review filter returns two unresolved benefits');
  await page.getByRole('tab',{name:/해당 없음/}).click();
  await verify(async () => await page.locator('.kl-benefit-card').count()===1, 'ineligible filter returns tenure mismatch');
  await page.getByRole('tab',{name:/전체 혜택/}).click();
  await page.getByRole('textbox',{name:'혜택 검색',exact:true}).fill('존재하지않는항목');
  await verify(async () => await page.getByRole('heading',{name:'찾는 혜택이 보이지 않아요'}).isVisible(), 'benefits empty search has reset path');
  await page.getByRole('button',{name:'전체 혜택 보기',exact:true}).click();
  await shot('benefits-desktop');
  await page.getByRole('button',{name:'자녀 돌봄 지원금 자세히 보기'}).click();
  let dialog=page.getByRole('dialog');
  await verify(async () => await dialog.isVisible(), 'benefit detail drawer opens');
  await dialog.getByRole('tab',{name:'자격 조건'}).click();
  await verify(async () => await dialog.locator('.kl-condition-list .pass').count()===3, 'consented employment tenure and child age checks appear');
  await shot('conditions-desktop');
  await dialog.getByRole('tab',{name:'규정 근거'}).click();
  await verify(async () => (await dialog.innerText()).includes('[가상 규정]'), 'fictional source is explicitly labeled');
  await dialog.getByText('출처 정보 자세히 보기').click();
  await verify(async () => (await dialog.innerText()).includes('DEMO-childcare'), 'source metadata exposes only synthetic ID');
  await shot('source-desktop');
  await dialog.getByRole('button',{name:'신청 준비 시작'}).click();
  await verify(async () => await page.locator('.kl-preparation-card').count()===1, 'detail CTA creates preparation');
  await page.getByRole('button',{name:'이어서 준비하기'}).click();
  dialog=page.getByRole('dialog');
  const boxes=dialog.getByRole('checkbox');
  for(let i=0;i<await boxes.count();i++) await boxes.nth(i).check();
  await verify(async () => await dialog.getByText('준비 항목을 모두 확인했어요.').isVisible(), 'preparation checklist can be completed');
  await verify(async () => await dialog.getByRole('button',{name:/실제 신청/}).isDisabled(), 'actual submission remains disabled');
  await shot('preparation-drawer-desktop');
  await page.keyboard.press('Escape');
  await verify(async () => await page.getByRole('dialog').count()===0, 'Escape dismisses native modal');
  await shot('preparations-desktop');
  await nav('AI 어시스턴트');
  await shot('assistant-welcome-desktop');
  await page.getByRole('button',{name:/자녀 돌봄 지원금 조건이 궁금해요/}).click();
  await page.locator('.kl-chat-message.assistant').first().waitFor();
  await verify(async () => (await page.locator('.kl-chat-message.assistant').innerText()).includes('예시 답변'), 'AI reply is labeled example');
  await page.locator('.kl-citation').click();
  await verify(async () => await page.getByRole('heading',{name:'답변의 근거'}).isVisible(), 'AI citation opens source panel');
  await shot('assistant-source-desktop');
  await page.getByRole('button',{name:'근거 패널 닫기'}).click();
  await page.getByRole('textbox',{name:'AI에게 질문하기'}).fill('연결되지 않은 주식 가격 질문');
  await page.keyboard.press('Enter');
  await page.locator('.kl-chat-message.assistant').nth(1).waitFor();
  await verify(async () => (await page.locator('.kl-chat-message.assistant').nth(1).innerText()).includes('회사 규정은 연결 전'), 'unsupported query does not invent a policy answer');
  await nav('규정·양식');
  await verify(async () => await page.locator('.kl-document-row').count()===12, 'library lists six fictional rules and six form types');
  await shot('library-desktop');
  await page.getByRole('tab',{name:'신청 양식',exact:true}).click();
  await verify(async () => await page.locator('.kl-document-row').count()===6, 'requested six form types are navigable');
  await page.locator('.kl-document-row').filter({hasText:'휴가신청서'}).click();
  dialog=page.getByRole('dialog');
  await verify(async () => (await dialog.innerText()).includes('다운로드·제출 연결 전'), 'form modal does not pretend to provide an official form');
  await shot('form-desktop');
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+k');
  dialog=page.getByRole('dialog');
  await dialog.getByRole('textbox',{name:'통합 검색어'}).fill('출장');
  await dialog.getByRole('button',{name:'검색',exact:true}).click();
  await verify(async () => await page.locator('.kl-document-row').count()===2, 'global search finds travel approval and settlement');
  await page.getByRole('link',{name:'내 정보 관리',exact:true}).click();
  await shot('profile-desktop');
  await page.getByRole('combobox',{name:'고용형태',exact:true}).selectOption('');
  await page.getByRole('button',{name:/조건 저장하고 혜택 다시 보기/}).click();
  await verify(async () => (await page.locator('.kl-benefit-card').filter({hasText:'오래 함께한 당신에게'}).locator('.kl-card-reason').innerText()).includes('10년 이상'), 'known failed tenure takes priority over unknown employment in the reason');
  await page.getByRole('link',{name:'내 정보 관리',exact:true}).click();
  await page.getByRole('combobox',{name:'고용형태',exact:true}).selectOption('regular');
  await page.getByRole('checkbox',{name:/가족 정보를 추천에 사용하는 데 동의/}).uncheck();
  await page.getByRole('button',{name:/조건 저장하고 혜택 다시 보기/}).click();
  await nav('나의 혜택');
  let childcare=page.locator('.kl-benefit-card').filter({hasText:'자녀 돌봄 지원금'});
  await verify(async () => (await childcare.innerText()).includes('추가 확인'), 'family consent off yields unknown instead of ineligible');
  await page.getByRole('link',{name:'내 정보 관리',exact:true}).click();
  await page.getByRole('checkbox',{name:/가족 정보를 추천에 사용하는 데 동의/}).check();
  await page.getByRole('checkbox',{name:'자녀 없음',exact:true}).check();
  await page.getByRole('button',{name:/조건 저장하고 혜택 다시 보기/}).click();
  await nav('나의 혜택');
  childcare=page.locator('.kl-benefit-card').filter({hasText:'자녀 돌봄 지원금'});
  await verify(async () => (await childcare.innerText()).includes('해당 없음'), 'explicit no children yields ineligible');
  await page.getByRole('link',{name:'내 정보 관리',exact:true}).click();
  await page.getByRole('button',{name:/모든 동의 철회 및 조건 삭제/}).click();
  await page.getByRole('dialog').getByRole('button',{name:'동의 철회 및 삭제',exact:true}).click();
  await verify(async () => !await page.getByRole('checkbox',{name:/근무 정보를 추천에 사용하는 데 동의/}).isChecked(), 'revocation clears consent');
  await nav('나의 혜택');
  await verify(async () => await page.locator('.kl-benefit-card .kl-badge.needs_review').count()===6, 'revocation yields six review results');
  await nav('신청 준비');
  await verify(async () => await page.locator('.kl-preparation-card').count()===0, 'revocation removes preparation records');
  await nav('AI 어시스턴트');
  await verify(async () => await page.locator('.kl-chat-message').count()===0, 'revocation removes example conversation');
  await page.getByRole('link',{name:'내 정보 관리',exact:true}).click();
  await page.getByRole('button',{name:'처음 예시로 초기화'}).click();
  await nav('홈');
  await page.getByRole('button',{name:'안내',exact:true}).click();
  await page.getByRole('link',{name:/로그인 화면도 살펴보기/}).click();
  await verify(async () => await page.getByRole('heading',{name:'오늘도 반가워요'}).isVisible(), 'login preview opens');
  await verify(async () => await page.locator('input[type=password]').count()===0, 'preview login does not collect credentials');
  await shot('login-desktop');
  await page.getByRole('link',{name:'가상 직원으로 둘러보기'}).click();
  await verify(async () => await page.locator('.kl-benefit-card').count()===3, 'preview login returns to initialized home');
  await verify(async () => errors.length===0, 'no browser runtime errors');
  await verify(async () => dataRequests.length===0, 'no API model or third-party requests');
  return {checks,errors,dataRequests,count:checks.length};
}
